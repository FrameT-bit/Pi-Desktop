
use std::cell::{Cell, RefCell};
use std::path::PathBuf;
use std::rc::Rc;

use gtk::prelude::*;

use crate::artifacts::{self, Artifact, ArtifactKind};
use crate::icons::{self, Tone};

#[derive(Clone, Copy, PartialEq, Eq)]
enum Filter {
    All,
    Image,
    File,
    Link,
}

impl Filter {
    fn matches(self, kind: ArtifactKind) -> bool {
        match self {
            Self::All => true,
            Self::Image => kind == ArtifactKind::Image,
            Self::File => kind == ArtifactKind::File,
            Self::Link => kind == ArtifactKind::Link,
        }
    }
}

pub struct ArtifactsUi {
    pub root: gtk::Box,
    agent_dir: PathBuf,
    search: gtk::Entry,
    filters: [gtk::ToggleButton; 4],
    list: gtk::Box,
    empty: gtk::Label,
    status: gtk::Label,
    all: RefCell<Vec<Artifact>>,
    filter: Cell<Filter>,
    busy: Cell<bool>,
    count: Cell<usize>,
    on_count: RefCell<Option<Box<dyn Fn(usize)>>>,
}

impl ArtifactsUi {
    pub fn build(agent_dir: PathBuf) -> Rc<Self> {
        let root = gtk::Box::new(gtk::Orientation::Vertical, 0);
        root.add_css_class("artifacts-page");
        root.set_hexpand(true);
        root.set_vexpand(true);

        let inner = gtk::Box::new(gtk::Orientation::Vertical, 12);
        inner.add_css_class("artifacts-inner");
        inner.set_hexpand(true);
        inner.set_vexpand(true);

        let title = gtk::Label::new(Some("Artifacts"));
        title.add_css_class("panel-title");
        title.set_xalign(0.0);
        let subtitle = gtk::Label::new(Some(
            "images, files and links generated by recent sessions",
        ));
        subtitle.add_css_class("artifacts-subtitle");
        subtitle.set_xalign(0.0);
        let heading = gtk::Box::new(gtk::Orientation::Vertical, 4);
        heading.append(&title);
        heading.append(&subtitle);

        let refresh = gtk::Button::with_label("update");
        refresh.add_css_class("git-btn");
        let head = gtk::Box::new(gtk::Orientation::Horizontal, 8);
        head.append(&heading);
        let spacer = gtk::Box::new(gtk::Orientation::Horizontal, 0);
        spacer.set_hexpand(true);
        head.append(&spacer);
        head.append(&refresh);
        inner.append(&head);

        let search = gtk::Entry::new();
        search.add_css_class("artifacts-search");
        search.set_placeholder_text(Some("filter by name, path, link or session..."));
        search.set_hexpand(true);
        inner.append(&search);

        let filter_bar = gtk::Box::new(gtk::Orientation::Horizontal, 6);
        filter_bar.add_css_class("artifacts-filters");
        let labels = ["all", "images", "files", "links"];
        let mut filters = Vec::new();
        let mut group: Option<gtk::ToggleButton> = None;
        for (index, label) in labels.iter().enumerate() {
            let button = gtk::ToggleButton::with_label(label);
            button.add_css_class("artifact-filter");
            match &group {
                Some(first) => button.set_group(Some(first)),
                None => group = Some(button.clone()),
            }
            if index == 0 {
                button.set_active(true);
            }
            filter_bar.append(&button);
            filters.push(button);
        }
        inner.append(&filter_bar);

        let status = gtk::Label::new(None);
        status.add_css_class("artifacts-status");
        status.set_xalign(0.0);
        status.set_visible(false);
        inner.append(&status);

        let list = gtk::Box::new(gtk::Orientation::Vertical, 0);
        list.add_css_class("artifacts-list");
        let empty = gtk::Label::new(Some(
            "no artifacts yet — request an image/archive or paste a link to the chat",
        ));
        empty.add_css_class("artifacts-empty");
        empty.set_xalign(0.0);
        empty.set_wrap(true);
        empty.set_visible(false);
        list.append(&empty);
        let scroll = gtk::ScrolledWindow::builder()
            .hscrollbar_policy(gtk::PolicyType::Never)
            .vscrollbar_policy(gtk::PolicyType::Automatic)
            .vexpand(true)
            .child(&list)
            .build();
        scroll.add_css_class("artifacts-scroll");
        inner.append(&scroll);
        root.append(&inner);

        let filters: [gtk::ToggleButton; 4] =
            [filters[0].clone(), filters[1].clone(), filters[2].clone(), filters[3].clone()];
        let this = Rc::new(Self {
            root,
            agent_dir,
            search,
            filters,
            list,
            empty,
            status,
            all: RefCell::new(Vec::new()),
            filter: Cell::new(Filter::All),
            busy: Cell::new(false),
            count: Cell::new(0),
            on_count: RefCell::new(None),
        });
        this.wire(&refresh);
        this.refresh();
        this
    }

    fn wire(self: &Rc<Self>, refresh: &gtk::Button) {
        {
            let me = self.clone();
            refresh.connect_clicked(move |_| me.refresh());
        }
        {
            let me = self.clone();
            self.search.connect_changed(move |_| me.render());
        }
        for (index, filter) in self.filters.iter().enumerate() {
            let me = self.clone();
            let value = match index {
                1 => Filter::Image,
                2 => Filter::File,
                3 => Filter::Link,
                _ => Filter::All,
            };
            filter.connect_toggled(move |button| {
                if button.is_active() {
                    me.filter.set(value);
                    me.render();
                }
            });
        }
    }

    pub fn set_on_count(&self, callback: impl Fn(usize) + 'static) {
        *self.on_count.borrow_mut() = Some(Box::new(callback));
        self.notify_count();
    }

    fn notify_count(&self) {
        if let Some(callback) = self.on_count.borrow().as_ref() {
            callback(self.count.get());
        }
    }

    pub fn refresh(self: &Rc<Self>) {
        if self.busy.get() {
            return;
        }
        self.busy.set(true);
        self.status.set_text("Reading sessions...");
        self.status.set_visible(true);
        let agent_dir = self.agent_dir.clone();
        let (tx, rx) = async_channel::bounded::<Vec<Artifact>>(1);
        std::thread::spawn(move || {
            let _ = tx.send_blocking(artifacts::scan(&agent_dir, 30));
        });
        let me = self.clone();
        glib::spawn_future_local(async move {
            let Ok(items) = rx.recv().await else {
                me.busy.set(false);
                return;
            };
            me.busy.set(false);
            me.count.set(items.len());
            *me.all.borrow_mut() = items;
            me.render();
            me.notify_count();
        });
    }

    fn query(&self) -> String {
        self.search.text().trim().to_lowercase()
    }

    fn render(self: &Rc<Self>) {
        while let Some(child) = self.list.first_child() {
            if child == self.empty {
                break;
            }
            self.list.remove(&child);
        }
        let mut child = self.list.first_child();
        while let Some(widget) = child {
            let next = widget.next_sibling();
            if widget != self.empty {
                self.list.remove(&widget);
            }
            child = next;
        }
        let query = self.query();
        let filter = self.filter.get();
        let all = self.all.borrow();
        let shown: Vec<&Artifact> = all
            .iter()
            .filter(|artifact| filter.matches(artifact.kind))
            .filter(|artifact| {
                query.is_empty()
                    || artifact.label.to_lowercase().contains(&query)
                    || artifact.value.to_lowercase().contains(&query)
                    || artifact.session_title.to_lowercase().contains(&query)
            })
            .collect();
        self.empty.set_visible(shown.is_empty());
        for artifact in shown {
            self.list.append(&row(artifact));
        }
        self.status.set_text(&format!(
            "{} artifact(s) · {} session(s)",
            self.count.get(),
            all.iter()
                .map(|artifact| artifact.session_id.as_str())
                .collect::<std::collections::HashSet<_>>()
                .len()
        ));
        self.status.set_visible(true);
    }
}

fn row(artifact: &Artifact) -> gtk::Box {
    let row = gtk::Box::new(gtk::Orientation::Horizontal, 10);
    row.add_css_class("artifact-row");

    let icon = match artifact.kind {
        ArtifactKind::Image => icons::icon("box", Tone::Muted),
        ArtifactKind::File => icons::icon("file", Tone::Muted),
        ArtifactKind::Link => icons::icon("export", Tone::Muted),
    };
    icon.add_css_class("artifact-icon");
    row.append(&icon);

    let info = gtk::Box::new(gtk::Orientation::Vertical, 2);
    info.set_hexpand(true);
    let label = gtk::Label::new(Some(&artifact.label));
    label.add_css_class("artifact-label");
    label.set_xalign(0.0);
    label.set_ellipsize(gtk::pango::EllipsizeMode::Middle);
    let meta = gtk::Label::new(Some(&format!(
        "{} · {} · {}",
        artifact.kind.label(),
        artifact.session_title,
        artifact.value
    )));
    meta.add_css_class("artifact-meta");
    meta.set_xalign(0.0);
    meta.set_ellipsize(gtk::pango::EllipsizeMode::Middle);
    meta.set_tooltip_text(Some(&artifact.value));
    info.append(&label);
    info.append(&meta);
    row.append(&info);

    let open = gtk::Button::with_label("open");
    open.add_css_class("git-mini");
    let value = artifact.value.clone();
    open.connect_clicked(move |_| {
        if let Err(error) = std::process::Command::new("xdg-open")
            .arg(&value)
            .spawn()
        {
            eprintln!("artifacts: failure to open {value}: {error}");
        }
    });
    row.append(&open);
    row
}
